#!/usr/bin/env bash
# Resume mixed EIL/MIU RL from the creative SFT checkpoint at step 479.
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"
LOCAL_ROOT="${LOYAL_LOCAL_RUN_ROOT:-/tmp/experiment_g_longtask_101}"
POST_ROOT="${LOYAL_PHASE1_POST_ROOT:-${LOCAL_ROOT}/evaluations/phase1-lambda050-e2m1-rollout200_posttrain}"
