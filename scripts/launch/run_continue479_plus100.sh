OLD_CKPT="${LOYAL_CONTINUE479_LOAD:-${LOCAL_ROOT}/checkpoints/mixed-v2-phase1-lambda050-e2m1-rollout200-phase1-seed1234-creative-sft}"
NEW_CKPT="${LOYAL_CONTINUE479_SAVE:-${LOCAL_ROOT}/checkpoints/mixed-v2-phase1-lambda050-e2m1-rollout200-phase1-seed1234-continue479-plus100}"
RAY_TEMP_DIR="${LOYAL_RAY_TEMP_DIR:-/tmp/rp479}"
DRY_RUN="${LOYAL_LONGTASK_DRY_RUN:-${LOYAL_SUBMIT_DRY_RUN:-0}}"

mkdir -p "${POST_ROOT}" "${NEW_CKPT}" "${RAY_TEMP_DIR}"
cd "${PROJECT_ROOT}"

if [[ "${DRY_RUN}" == "1" ]]; then
  cat <<EOF
DRY_RUN script=${BASH_SOURCE[0]}
DRY_RUN ray_temp_dir=${RAY_TEMP_DIR}
DRY_RUN source_checkpoint=${OLD_CKPT}
DRY_RUN target_checkpoint=${NEW_CKPT}
DRY_RUN launch=bash scripts/launch/run_training_host.sh mixed
EOF
  exit 0
fi

latest_file="${OLD_CKPT}/latest_checkpointed_iteration.txt"
if [[ ! -s "${latest_file}" ]]; then
  echo "missing source checkpoint tracker: ${latest_file}" >&2
  exit 7
fi
if [[ "$(tr -d '[:space:]' <"${latest_file}")" != "479" ]]; then
  echo "source checkpoint latest is not 479: $(cat "${latest_file}")" >&2
  exit 7
fi
if [[ ! -f "${OLD_CKPT}/iter_0000479/common.pt" || ! -f "${OLD_CKPT}/iter_0000479/.metadata" ]]; then
  echo "source checkpoint iter_0000479 is incomplete under ${OLD_CKPT}" >&2
  exit 7
fi
if [[ ! -s "${RUN_DIR}/mixed_train.jsonl" ]]; then
  echo "missing mixed train data: ${RUN_DIR}/mixed_train.jsonl" >&2
  exit 7
fi
if [[ "${LOYAL_MIXED_NO_LOAD_OPTIM:-0}" == "1" || "${LOYAL_MIXED_NO_LOAD_RNG:-0}" == "1" ]]; then
  echo "unsafe strict step479 resume: refusing no-load optimizer/RNG" >&2
  exit 7
fi

